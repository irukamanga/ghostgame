const assert=require('node:assert/strict');
const R=require('./amida-rules.js');
assert.equal(R.canAdd([],6,0),false);
assert.equal(R.canAdd([{row:0,gap:2}],0,3),false);
assert.equal(R.canAdd([{row:0,gap:1}],0,3),true);
const bars=[{row:0,gap:3},{row:1,gap:2},{row:2,gap:1}];
assert.equal(R.trace(bars,4).end,1);
assert.equal(R.trace(bars,3).end,4);
assert.equal(R.trace(bars,4).used.length,3);
let r=R.outcome(2,3,false,2,true);
assert.deepEqual([r.score,r.cross,r.ripper,r.delta],[0,0,false,-2]);
r=R.outcome(0,3,false,1,true);
assert.deepEqual([r.score,r.cross,r.delta],[1,4,1]);
r=R.outcome(0,4,false,1,false);
assert.equal(r.ripper,true);assert.equal(r.cross,5);
r=R.outcome(r.score,r.cross,r.ripper,0,true);
assert.equal(r.score,0);assert.equal(r.cross,0);
assert.equal(R.allowance(16,1),0);
assert.equal(R.allowance(19,5),1);
assert.equal(R.winner({p:4,c:0},4),null);
assert.equal(R.winner({p:1,c:0},5),'p');
assert.equal(R.winner({p:1,c:1},5),'draw');
const used=new Set(R.trace(bars,4).used);
assert.equal(bars.filter(b=>!used.has(R.key(b))).length,0);
console.log('Amida common rules: 18 assertions passed');
